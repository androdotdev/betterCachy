import json
import re
import shutil
from pathlib import Path

from . import settings
from .paths import CONFIG, HOME
from .shell import run

IMAGE_EXT = {".jpg", ".jpeg", ".png", ".webp"}
HYPR_DIR = CONFIG / "hypr"
GENERATED = HYPR_DIR / "bettercachy.lua"
INCLUDE_LINE = 'require("bettercachy")'

PALETTE_DEFAULT = {
    "primary": "#ffb59b", "secondary": "#e7bdb0", "error": "#ffb4ab",
    "surface": "#1a110e", "surfaceContainer": "#271d1a", "surfaceContainerHigh": "#322825",
    "outline": "#a08d87", "fg": "#f1dfd9", "fgDim": "#d8c2bb", "fgPrimary": "#55200a",
}
HYPR_DEFAULTS = {
    "rounding": 8, "border_size": 1, "gaps_in": 6, "gaps_out": 12,
    "blur_enabled": True, "blur_size": 8, "blur_passes": 1,
}


# ---------- palette ----------
def palette() -> dict:
    pal = dict(PALETTE_DEFAULT)
    try:
        data = json.loads((CONFIG / "quickshell/colors.json").read_text())
        for key in pal:
            if isinstance(data.get(key), str):
                pal[key] = data[key]
    except Exception:  # noqa: BLE001
        pass
    return pal


# ---------- wallpapers ----------
def list_wallpapers(folder: str) -> list:
    root = Path(folder).expanduser()
    if not root.is_dir():
        return []
    files = [p for p in sorted(root.rglob("*")) if p.suffix.lower() in IMAGE_EXT]
    return [{"path": str(p), "name": p.stem} for p in files[:240]]


def apply_wallpaper(path: str, lock: bool) -> str:
    script = HOME / ".local/bin/theme-apply"
    if not script.exists():
        found = shutil.which("theme-apply")
        if not found:
            return "theme-apply not found. Copy home/ into $HOME first."
        script = Path(found)
    cmd = [str(script)] + (["-l"] if lock else []) + [path]
    rc, out, err = run(cmd, timeout=120)
    if rc == 0:
        settings.update(last_wallpaper=path, lock=lock)
        return "Theme applied"
    return "theme-apply failed: " + (err.strip() or out.strip() or f"exit {rc}")[-300:]


# ---------- hyprland values ----------
def _grab(text: str, pattern: str):
    m = re.search(pattern, text)
    return m.group(1) if m else None


def read_hypr() -> dict:
    """Effective values: hyprland.lua, then hyprland-settings.lua, then bettercachy.lua."""
    values = dict(HYPR_DEFAULTS)
    for name in ("hyprland.lua", "hyprland-settings.lua", "bettercachy.lua"):
        try:
            text = (HYPR_DIR / name).read_text()
        except OSError:
            continue
        for key in ("rounding", "border_size", "gaps_in", "gaps_out"):
            v = _grab(text, rf"\b{key}\s*=\s*(\d+)")
            if v is not None:
                values[key] = int(v)
        blur = re.search(r"blur\s*=\s*\{([^}]*)\}", text)
        if blur:
            body = blur.group(1)
            enabled = _grab(body, r"enabled\s*=\s*(true|false)")
            if enabled:
                values["blur_enabled"] = enabled == "true"
            for key in ("size", "passes"):
                v = _grab(body, rf"\b{key}\s*=\s*(\d+)")
                if v is not None:
                    values["blur_" + key] = int(v)
    return values


def write_hypr(values: dict) -> str:
    v = {**HYPR_DEFAULTS, **values}
    lua = (
        "-- Generated by bettercachy-ctl. Change values in the app; edits here are overwritten.\n"
        "hl.config({\n"
        "    general = {\n"
        f"        border_size = {int(v['border_size'])},\n"
        f"        gaps_in = {int(v['gaps_in'])},\n"
        f"        gaps_out = {int(v['gaps_out'])},\n"
        "    },\n"
        "    decoration = {\n"
        f"        rounding = {int(v['rounding'])},\n"
        "        blur = {\n"
        f"            enabled = {'true' if v['blur_enabled'] else 'false'},\n"
        f"            size = {int(v['blur_size'])},\n"
        f"            passes = {int(v['blur_passes'])},\n"
        "        },\n"
        "    },\n"
        "})\n"
    )
    HYPR_DIR.mkdir(parents=True, exist_ok=True)
    GENERATED.write_text(lua)
    note = ensure_include()
    rc, _, err = run(["hyprctl", "reload"], timeout=10)
    return ("Hyprland settings applied. " + note) if rc == 0 else (
        "Saved, but could not reload Hyprland: " + (err.strip() or f"exit {rc}"))


def include_present() -> bool:
    try:
        return INCLUDE_LINE in (HYPR_DIR / "hyprland.lua").read_text()
    except OSError:
        return False


def ensure_include() -> str:
    """Make hyprland.lua load bettercachy.lua (last line, so it wins). Backs up first."""
    main = HYPR_DIR / "hyprland.lua"
    if not main.exists():
        return "hyprland.lua not found."
    text = main.read_text()
    if INCLUDE_LINE in text:
        return ""
    shutil.copy2(main, main.with_suffix(".lua.bak"))
    main.write_text(text.rstrip("\n") + "\n\n-- added by bettercachy-ctl\n" + INCLUDE_LINE + "\n")
    return "Added require(\"bettercachy\") to hyprland.lua (backup: hyprland.lua.bak)."
